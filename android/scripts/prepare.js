const fs = require('fs');
const path = require('path');
const babel = require('@babel/core');
const sourcePath = path.resolve(__dirname, '../../index.html');
const targetPath = path.resolve(__dirname, '../app/src/main/assets/index.html');
let html = fs.readFileSync(sourcePath, 'utf8');
const startTag = '<script type="module">';
const start = html.indexOf(startTag);
if (start < 0) throw new Error('Could not find the game module in root index.html.');
const codeStart = start + startTag.length;
const end = html.indexOf('</script>', codeStart);
if (end < 0) throw new Error('Could not find the end of the game module.');
let js = html.slice(codeStart, end);
js = js.split('\n').filter(line => !line.trim().startsWith('import * as THREE from ')).join('\n');
js = js.replace('new THREE.CapsuleGeometry(.38,.72,4,8)', 'new THREE.CylinderGeometry(.34,.38,.95,8)');
const compiled = babel.transformSync(js, { presets: [[require.resolve('@babel/preset-env'), { targets: { ie: '11' }, bugfixes: true }]], comments: false }).code;
const replacement = '<script src="https://cdn.jsdelivr.net/npm/three@0.110.0/build/three.min.js"></script>\n<script>\n' + compiled + '\n</script>';
html = html.slice(0, start) + replacement + html.slice(end + '</script>'.length);
fs.mkdirSync(path.dirname(targetPath), { recursive: true });
fs.writeFileSync(targetPath, html);
console.log('Prepared game HTML for older Android WebView.');
